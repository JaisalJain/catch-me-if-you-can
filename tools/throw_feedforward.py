#!/usr/bin/env python3
"""Precompute inverse-dynamics feed-forward torques for the configured throw (offline, venv + MuJoCo).

    source install/setup.bash   # (not required)
    env -u PYTHONPATH .venv/bin/python tools/throw_feedforward.py

tau_ff(t) = M(q) qdd + c(q, qd) for arm A carrying a 60 g cube on the palm, gravity EXCLUDED (the sim
compensates gravity inside MuJoCo through the actuators). Sampled at the plan's own samples and written to
src/catch_throw/config/throw_ff.yaml with a hash of throw.yaml + scene/physics/poses so throw_node can refuse a
stale table. The JTC adds the point's `effort` field to its PD output (effort command interface).
"""
import hashlib
import os
import sys

import mujoco
import numpy as np
import yaml

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
for p in ("src/catch_kinematics", "src/catch_ballistics", "src/catch_throw", "src/catch_description/scripts", "tools"):
    sys.path.insert(0, os.path.join(REPO, p))
import feasibility as F  # noqa: E402

HASHED = ["src/catch_throw/config/throw.yaml", "src/catch_description/config/scene.yaml",
          "src/catch_description/config/physics.yaml"]


def inputs_hash(root=REPO):
    """Hash of everything the trajectory depends on: throw.yaml without the gripper `release` timing section,
    plus scene.yaml and physics.yaml (same function in catch_throw/throw_node.py)."""
    cfg = yaml.safe_load(open(os.path.join(root, HASHED[0])))["throw"]
    cfg.pop("release", None)
    h = hashlib.sha256(yaml.safe_dump(cfg, sort_keys=True).encode())
    for f in HASHED[1:]:
        h.update(open(os.path.join(root, f), "rb").read())
    return h.hexdigest()[:16]


def plan_from_yaml():
    from catch_ballistics import velocity_for_launch_angle
    from catch_throw.generator import generate_throw
    from catch_throw.profile import ProfileParams
    cfg = yaml.safe_load(open(os.path.join(REPO, "src/catch_throw/config/throw.yaml")))["throw"]
    scene, phys, robots = F.load()
    p, c = np.array(cfg["release_point"]), np.array(cfg["catch_point"])
    v, _ = velocity_for_launch_angle(p, c, np.radians(cfg["launch_angle_deg"]))
    plan = generate_throw(robots["a"], p, v, cfg["q_release_seed"], ProfileParams(**cfg["profile"]),
                          finger_axis=cfg["finger_axis"], pitch_rate=cfg["pitch_rate"], dt=cfg["sample_dt"])
    return plan, scene, phys


def main():
    plan, scene, phys = plan_from_yaml()
    dyn = F.Dynamics(scene, phys)
    dyn.m.opt.gravity[:] = 0.0          # gravity is compensated inside the sim
    tau = dyn.torques(plan.q, plan.qd, plan.qdd)
    out = dict(inputs_hash=inputs_hash(), dt=float(plan.t[1] - plan.t[0]), n=len(plan.t),
               note="tau_ff = M qdd + c(q,qd), gravity excluded; generated by tools/throw_feedforward.py",
               tau=np.round(tau, 4).tolist())
    path = os.path.join(REPO, "src/catch_throw/config/throw_ff.yaml")
    yaml.safe_dump(out, open(path, "w"), default_flow_style=None, width=200)
    print(f"wrote {path}: {len(plan.t)} samples, |tau|max per joint {np.round(np.abs(tau).max(axis=0), 1).tolist()} N m")


if __name__ == "__main__":
    main()
