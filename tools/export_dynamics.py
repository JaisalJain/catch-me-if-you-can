#!/usr/bin/env python3
"""Export UR5e + 2F-85 rigid-body parameters from the compiled MuJoCo model for catch_kinematics.dynamics (numpy
RNEA used by the ROS nodes for torque checks and feed-forward), plus a test fixture of mj_inverse torques.

    env -u PYTHONPATH .venv/bin/python tools/export_dynamics.py

Model = tools/feasibility.py Dynamics (one arm, gravity compensation off) WITHOUT the 60 g cube (B intercepts with
an empty hand). Every body below wrist_3 (gripper at knuckle 0) is lumped onto wrist_3 (rigid at the pose of the
open gripper; the finger links weigh < 0.12 kg in total). Joint placements are the compiled MuJoCo body poses
relative to the parent body at q = 0; armature (rotor inertia) per joint. Verified: same torques as mj_inverse
(test fixture, src/catch_kinematics/test/test_dynamics.py).
Output: src/catch_kinematics/config/ur5e_dynamics.yaml, src/catch_kinematics/test/dynamics_fixture.json
"""
import json
import os
import sys

import mujoco
import numpy as np
import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import v2_common as V  # noqa: E402

LINKS = ["shoulder_link", "upper_arm_link", "forearm_link", "wrist_1_link", "wrist_2_link", "wrist_3_link"]


def model():
    scene, phys = V.build_mjcf.load_cfg()
    phys = dict(phys, arm={"gravcomp": False})
    arm = V.build_mjcf.make_arm(scene, phys)
    for b in arm.bodies:
        b.gravcomp = 0.0
    spec = mujoco.MjSpec()
    fr = spec.worldbody.add_frame(pos=[0, 0, 0])
    spec.attach(arm, prefix="", frame=fr)
    assets = os.path.join(V.REPO, "src/catch_description/mjcf/assets")
    for m in spec.meshes:
        m.file = os.path.join(assets, m.file)
    m = spec.compile()
    return m


def main():
    m = model()
    d = mujoco.MjData(m)
    mujoco.mj_forward(m, d)
    bid = lambda n: mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_BODY, n)
    T = lambda b: (d.xpos[b].copy(), d.xmat[b].reshape(3, 3).copy())
    out = dict(note="generated by tools/export_dynamics.py from the compiled MuJoCo model (Menagerie UR5e + 2F-85, "
                    "gripper lumped onto wrist_3, no payload); link frames = MuJoCo body frames", gravity=[0, 0, -9.81],
               joints=[])
    prev_p, prev_R = T(bid("base"))
    for jn, ln in zip(V.JN, LINKS):
        b = bid(ln)
        p, R = T(b)
        j = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, jn)
        mass, com = float(m.body_mass[b]), m.body_ipos[b].copy()
        q = np.zeros(4)
        Ri = np.zeros(9)
        mujoco.mju_quat2Mat(Ri, m.body_iquat[b])
        Ri = Ri.reshape(3, 3)
        I = Ri @ np.diag(m.body_inertia[b]) @ Ri.T        # about the COM, in the link frame
        if ln == "wrist_3_link":
            # lump all descendants (spatial inertia sum about the link origin, then back to the COM)
            M, mc, Io = mass, mass * com, I + mass * (np.dot(com, com) * np.eye(3) - np.outer(com, com))
            for c in range(m.nbody):
                a, inside = c, False
                while a > 0:
                    a = m.body_parentid[a]
                    if a == b:
                        inside = True
                        break
                if not inside or m.body_mass[c] == 0:
                    continue
                Rc = R.T @ d.ximat[c].reshape(3, 3)              # principal frame of c in the link frame
                rc = R.T @ (d.xipos[c] - p)                      # COM of c in the link frame
                Ic = Rc @ np.diag(m.body_inertia[c]) @ Rc.T
                mc_ = m.body_mass[c]
                M += mc_
                mc = mc + mc_ * rc
                Io = Io + Ic + mc_ * (np.dot(rc, rc) * np.eye(3) - np.outer(rc, rc))
            com = mc / M
            I = Io - M * (np.dot(com, com) * np.eye(3) - np.outer(com, com))
            mass = M
        out["joints"].append(dict(
            name=jn, child_link=ln, R_parent=np.round(prev_R.T @ R, 12).tolist(),
            p_parent=np.round(prev_R.T @ (p - prev_p), 12).tolist(), axis=m.jnt_axis[j].tolist(),
            mass=float(mass), com=np.round(com, 12).tolist(), inertia=np.round(I, 12).tolist(),
            armature=float(m.dof_armature[m.jnt_dofadr[j]])))
        prev_p, prev_R = p, R
    path = os.path.join(V.REPO, "src/catch_kinematics/config/ur5e_dynamics.yaml")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    yaml.safe_dump(out, open(path, "w"), default_flow_style=None, width=200)
    # fixture: mj_inverse on random states
    dofs = [m.jnt_dofadr[mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, j)] for j in V.JN]
    qadr = [m.jnt_qposadr[mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, j)] for j in V.JN]
    rng = np.random.default_rng(0)
    fx = []
    # rigid-body reference: the gripper linkage's soft equality constraints are disabled (the lumped model has none;
    # at aggressive random states they otherwise add large spurious forces to mj_inverse)
    m.opt.disableflags |= mujoco.mjtDisableBit.mjDSBL_CONSTRAINT
    for k in range(20):
        q, qd, qdd = rng.uniform(-3, 3, 6), rng.uniform(-2.5, 2.5, 6), rng.uniform(-30, 30, 6)
        d.qpos[:] = 0
        d.qvel[:] = 0
        d.qacc[:] = 0
        d.qpos[qadr], d.qvel[dofs], d.qacc[dofs] = q, qd, qdd
        mujoco.mj_inverse(m, d)
        fx.append(dict(q=q.tolist(), qd=qd.tolist(), qdd=qdd.tolist(), tau=d.qfrc_inverse[dofs].tolist()))
    json.dump(fx, open(os.path.join(V.REPO, "src/catch_kinematics/test/dynamics_fixture.json"), "w"), indent=0)
    print("wrote", path, "and the fixture; total mass", sum(j["mass"] for j in out["joints"]))


if __name__ == "__main__":
    main()
